package org.example;

public class ExerciseMethods {


    // Metodo para verificar se o número é múltiplo de 5
    public void verificarMultiploDeCinco(int numero) {
        if (numero % 5 == 0) {
            System.out.println("O número " + numero + " é múltiplo de 5.");
        } else {
            System.out.println("O número " + numero + " não é múltiplo de 5.");
        }
    }
}
